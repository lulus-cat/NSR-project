/** "2026-08-25" → 그날의 한 줄. 같은 날엔 항상 같은 문장이 나온다. */
export function dailyQuote(dateString: string): DailyQuote {
  let h = 0;
  for (let i = 0; i < dateString.length; i++) h = (h * 31 + dateString.charCodeAt(i)) >>> 0;
  return QUOTES[h % QUOTES.length];
}
