/**
 * 직장 내 괴롭힘 탐지 패턴.
 *
 * 법적 기준
 * --------
 * 근로기준법 제76조의2는 직장 내 괴롭힘을 이렇게 정의한다.
 *   "사용자 또는 근로자가 직장에서의 지위 또는 관계 등의 우위를 이용하여
 *    업무상 적정범위를 넘어 다른 근로자에게 신체적·정신적 고통을 주거나
 *    근무환경을 악화시키는 행위"
 *
 * 세 가지 요건이 모두 필요하다.
 *   (1) 우위성   - 선배/프리셉터/관리자는 관계 우위가 인정되기 쉽다
 *   (2) 업무상 적정범위 초과 - 여기가 교육과 괴롭힘이 갈리는 지점이다
 *   (3) 고통 또는 근무환경 악화
 *
 * 이 엔진이 하는 일과 못 하는 일
 * -----------------------------
 * 할 수 있는 것: (2)의 **후보**를 찾아 근거와 함께 모아준다.
 * 못 하는 것:   최종 판단. 어조, 표정, 맥락, 관계사, 반복성의 전모는 텍스트에 없다.
 *
 * 그래서 출력은 "점수"이자 **기록의 목록**이다. 점수만 보지 말고 인용문을 보라는
 * 전제로 UI가 설계되어 있다. 이 도구는 누구를 고발하기 위한 판정기가 아니라,
 * 나중에 말이 안 나오는 상황에서 "그때 무슨 말을 들었는지" 자기가 확인하기 위한 기록이다.
 *
 * 오탐을 줄이기 위한 장치
 *   - `exclude`: 같은 단어가 욕이 아닌 관용구로 쓰이는 경우를 뺀다 ("미친 듯이 바빴다")
 *   - 본인(self) 발화는 채점하지 않는다
 *   - 환자/보호자 발화는 별도 집계한다 (성격이 다른 문제이므로)
 */

export type HarassmentCategory =
  | "insult" // 인격 모독 / 욕설 / 비하
  | "public-shaming" // 공개 질책 / 망신주기
  | "threat" // 위협 / 불이익 암시
  | "excessive-demand" // 과도한 업무 부여 / 부당 지시
  | "exclusion" // 업무 배제 / 따돌림
  | "interrogation" // 답할 기회를 주지 않는 추궁
  | "personal-errand" // 사적 용무 지시
  | "comparison"; // 비교 / 낙인

export interface HarassmentPattern {
  category: HarassmentCategory;
  /** 1(경미) ~ 5(중대). 법적 평가가 아니라 이 도구 내부의 상대 가중치다. */
  severity: number;
  /** 이 패턴 자체의 신뢰도. 관용구와 겹칠수록 낮춘다. */
  confidence: number;
  match: RegExp;
  /** 이 정규식이 걸려도 함께 걸리면 무시할 표현. 관용구 오탐 방지. */
  exclude?: RegExp;
  /** 사용자에게 보여줄 설명. */
  label: string;
}

